"""SQL expressions over a want's name that the statement writing the name
must supply (`wants.name_folded` and `wants.name_query` are generated by
PostgreSQL)."""

from __future__ import annotations

from sqlalchemy import ScalarSelect, String, bindparam, func, literal, literal_column, select
from sqlalchemy import cast as sql_cast
from sqlalchemy.dialects.postgresql import TSQUERY

# A word this short has too few trigrams to be matched by similarity.
SHORT_WORD_MAX_LENGTH = 3


def short_words_query(name: str) -> ScalarSelect[str | None]:
    """The value of `wants.short_words_query` for `name`: an all-words
    `tsquery` of the lexemes of at most `SHORT_WORD_MAX_LENGTH` characters,
    `NULL` without any. The lexemes come from the parser that builds
    `products.search_vector`, so "3-5" gives `'3'` and `'-5'`."""
    vector = func.to_tsvector(
        literal_column("'simple'::regconfig"),
        func.fold_pl(bindparam(None, name, type_=String)),
    )
    lexeme = func.unnest(func.tsvector_to_array(vector)).column_valued("lexeme")
    # A quoted `tsquery` operand escapes `\` and `'` by doubling them.
    escaped = func.replace(func.replace(lexeme, "\\", "\\\\"), "'", "''")
    operand = literal("'") + escaped + literal("'")
    return (
        select(sql_cast(func.string_agg(operand, " & "), TSQUERY))
        .where(func.char_length(lexeme) <= SHORT_WORD_MAX_LENGTH)
        .scalar_subquery()
    )

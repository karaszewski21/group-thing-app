"""`app.wants` models (migration 0099). Cross-module references
(`parties.id`, `categories.id`, `localities.id`) are plain FK-id columns, and
the module declares no `relationship()` at all, per
`standards/backend/models.md`. `WantMatch.item_id` and
`Want.match_notification_id` are loose pointers without a foreign key.

Every timestamp is naive UTC (`standards/backend/time.md`). Rows are hard
deleted."""

from __future__ import annotations

import enum
import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    REAL,
    Boolean,
    CheckConstraint,
    Computed,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Integer,
    SmallInteger,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects import postgresql
from sqlalchemy.dialects.postgresql import TSQUERY
from sqlalchemy.orm import Mapped, mapped_column

from app.core.base_model import BaseEntity
from app.wants.domain.status import WantMatchSource, WantStatus


def _enum_column(enum_cls: type[enum.StrEnum], length: int) -> Enum:
    """See `app/party/models.py`'s identical helper for the full rationale."""
    return Enum(
        enum_cls,
        native_enum=False,
        length=length,
        values_callable=lambda cls: [member.value for member in cls],
    )


class Want(BaseEntity):
    __tablename__ = "wants"
    __table_args__ = (
        CheckConstraint(
            "radius_km IS NULL OR (locality_id IS NOT NULL AND radius_km BETWEEN 1 AND 100)",
            name="ck_wants_radius_requires_locality",
        ),
        CheckConstraint(
            "(status = 'ACTIVE') = (closed_at IS NULL)",
            name="ck_wants_closed_at_matches_status",
        ),
        Index("ix_wants_seeker_party_id_status", "seeker_party_id", "status"),
        Index(
            "ix_wants_active_expires_at",
            "expires_at",
            postgresql_where=text("status = 'ACTIVE'"),
        ),
        Index(
            "ix_wants_closed_at",
            "closed_at",
            postgresql_where=text("status <> 'ACTIVE'"),
        ),
    )

    seeker_party_id: Mapped[uuid.UUID] = mapped_column(
        postgresql.UUID(as_uuid=True),
        ForeignKey("parties.id", name="fk_wants_seeker_party_id_parties"),
        nullable=False,
    )
    name: Mapped[str] = mapped_column(String(80), nullable=False)
    note: Mapped[str | None] = mapped_column(String(300), nullable=True)
    category_id: Mapped[uuid.UUID | None] = mapped_column(
        postgresql.UUID(as_uuid=True),
        ForeignKey("categories.id", name="fk_wants_category_id_categories", ondelete="SET NULL"),
        nullable=True,
    )
    # `GIFT`, `SWAP` or `NULL` = either.
    offer_mode: Mapped[str | None] = mapped_column(String(20), nullable=True)
    locality_id: Mapped[str | None] = mapped_column(
        String(7),
        ForeignKey("localities.id", name="fk_wants_locality_id_localities", ondelete="RESTRICT"),
        nullable=True,
    )
    # `NULL` with a locality = that locality only.
    radius_km: Mapped[int | None] = mapped_column(SmallInteger, nullable=True)
    notifications_enabled: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=True, server_default=text("true")
    )
    status: Mapped[WantStatus] = mapped_column(_enum_column(WantStatus, 20), nullable=False)
    expires_at: Mapped[datetime] = mapped_column(DateTime(), nullable=False)
    # Set exactly while the want is not ACTIVE.
    closed_at: Mapped[datetime | None] = mapped_column(DateTime(), nullable=True)
    reminded_at: Mapped[datetime | None] = mapped_column(DateTime(), nullable=True)
    # Both generated by PostgreSQL, deferred with raiseload as
    # `Product.search_vector`.
    name_folded: Mapped[str] = mapped_column(
        Text,
        Computed("fold_pl(name)", persisted=True),
        nullable=False,
        deferred=True,
        deferred_raiseload=True,
    )
    name_query: Mapped[str] = mapped_column(
        TSQUERY,
        Computed("plainto_tsquery('simple'::regconfig, fold_pl(name))", persisted=True),
        nullable=False,
        deferred=True,
        deferred_raiseload=True,
    )
    # Written in SQL by the statement that writes `name`, never from Python.
    short_words_query: Mapped[str | None] = mapped_column(TSQUERY, nullable=True)
    match_notification_id: Mapped[uuid.UUID | None] = mapped_column(
        postgresql.UUID(as_uuid=True), nullable=True
    )
    match_notification_count: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default=text("0")
    )

    def __eq__(self, other: Any) -> bool:
        """No natural unique key exists (a seeker may repeat a name), so the
        business key is the immutable seeker plus creation time."""
        if not isinstance(other, Want):
            return NotImplemented
        return (self.seeker_party_id, self.created_at) == (
            other.seeker_party_id,
            other.created_at,
        )

    def __hash__(self) -> int:
        return hash((self.seeker_party_id, self.created_at))


class WantMatch(BaseEntity):
    """One listed item found for a want. `seen_at` `NULL` = new to the
    seeker."""

    __tablename__ = "want_matches"
    __table_args__ = (
        UniqueConstraint("want_id", "item_id", name="uq_want_matches_want_id_item_id"),
        Index("ix_want_matches_item_id", "item_id"),
    )

    want_id: Mapped[uuid.UUID] = mapped_column(
        postgresql.UUID(as_uuid=True),
        ForeignKey("wants.id", name="fk_want_matches_want_id_wants", ondelete="CASCADE"),
        nullable=False,
    )
    item_id: Mapped[uuid.UUID] = mapped_column(postgresql.UUID(as_uuid=True), nullable=False)
    source: Mapped[WantMatchSource] = mapped_column(
        _enum_column(WantMatchSource, 10), nullable=False
    )
    score: Mapped[float] = mapped_column(REAL, nullable=False)
    seen_at: Mapped[datetime | None] = mapped_column(DateTime(), nullable=True)
    opened_at: Mapped[datetime | None] = mapped_column(DateTime(), nullable=True)

    def __eq__(self, other: Any) -> bool:
        if not isinstance(other, WantMatch):
            return NotImplemented
        return (self.want_id, self.item_id) == (other.want_id, other.item_id)

    def __hash__(self) -> int:
        return hash((self.want_id, self.item_id))


class WantScanMarker(BaseEntity):
    """How far a periodic scan has read, one row per `scan_name`."""

    __tablename__ = "want_scan_markers"
    __table_args__ = (UniqueConstraint("scan_name", name="uq_want_scan_markers_scan_name"),)

    scan_name: Mapped[str] = mapped_column(String(30), nullable=False)
    scanned_through: Mapped[datetime] = mapped_column(DateTime(), nullable=False)

    def __eq__(self, other: Any) -> bool:
        if not isinstance(other, WantScanMarker):
            return NotImplemented
        return self.scan_name == other.scan_name

    def __hash__(self) -> int:
        return hash(self.scan_name)
